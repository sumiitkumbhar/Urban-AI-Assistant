export async function POST(req: Request) {
  const start = Date.now();
  const timer = createStageTimer();

  try {
    let body: RagRequest;

    const contentType = req.headers.get("content-type") || "";

    if (contentType.includes("application/json")) {
      body = (await req.json()) as RagRequest;
    } else if (contentType.includes("multipart/form-data")) {
      const form = await req.formData();
      body = {
        query: String(form.get("query") || ""),
        mode:
          (String(form.get("mode") || "auto") as
            | "auto"
            | "feasibility"
            | "permitting"
            | "risk") || "auto",
        drawingFile: (form.get("drawingFile") as File) || undefined,
        conversationId: (form.get("conversationId") as string) || undefined,
        visitorId: (form.get("visitorId") as string) || undefined,
        voiceMode: form.get("voiceMode") === "true",
      };
    } else {
      body = (await req.json()) as RagRequest;
    }

    if (!body?.query || typeof body.query !== "string") {
      return NextResponse.json(
        {
          success: false,
          error: "Invalid request: query is required",
        } satisfies RagResponse,
        { status: 400 }
      );
    }

    const rawQuery = body.query;

    // See GREETING FAST PATH above. Trade-off, taken deliberately: a
    // fast-pathed turn is NOT saved to conversation history (that write
    // happens further down, alongside searchRAG), so a follow-up
    // immediately after "Hi" won't see it in context. Acceptable for small
    // talk this low-stakes, and it's what keeps this genuinely instant
    // rather than one Supabase round-trip away from instant.
    const greetingFastPathReply = matchGreetingFastPath(rawQuery);
    if (greetingFastPathReply) {
      timer.mark("greeting_fast_path");
      timer.report({ path: "greeting_fast_path" });
      const fastPathVoiceMode = body.voiceMode === true;
      return NextResponse.json({
        success: true,
        answer: greetingFastPathReply,
        data: {
          citations: [],
          query: rawQuery,
          region: body.region ?? null,
          resultsCount: 0,
          references: { documents: [], web: [] },
          speechText: fastPathVoiceMode ? greetingFastPathReply : undefined,
        },
        metadata: {
          processing_time: Date.now() - start,
          confidence: 1,
          webFallbackUsed: false,
        },
      } satisfies RagResponse);
    }

    // Speech-to-text mangles domain jargon - "NPPF" comes back as "NPP" -
    // and because the transcript feeds BOTH retrieval and the answer
    // prompt, an uncorrected one makes the reply confidently discuss the
    // wrong term throughout. Correcting here, before anything downstream
    // reads `query`, fixes retrieval and the answer's wording in one move.
    // Only ever swaps in vocabulary this corpus actually contains; never
    // touches ordinary English. See lib/domain-vocabulary.ts.
    const { correctedQuery: query, corrections: termCorrections } =
      correctDomainTerms(rawQuery, { voiceMode: body.voiceMode === true });

    timer.mark("term_correction");

    if (termCorrections.length) {
      console.log(
        "🔤 Corrected domain terms:",
        termCorrections.map((c) => `${c.from} -> ${c.to}`).join(", ")
      );
    }

    const visitorId =
      typeof body.visitorId === "string" ? body.visitorId.trim() : "";
    const requestedConversationId =
      typeof body.conversationId === "string" ? body.conversationId.trim() : "";

    // conversationId stays null (and everything below becomes a no-op)
    // whenever visitorId is absent - callers that don't opt into
    // conversation memory get the exact same stateless behavior as
    // before this feature existed.
    let conversationId: string | null = null;
    let conversationHistory: ConversationTurn[] = [];

    if (visitorId) {
      conversationId = await ensureConversation(
        visitorId,
        requestedConversationId,
        query
      );
      if (conversationId) {
        conversationHistory = await loadRecentMessages(conversationId);
      }
    }

    // Retrieval gets a coreference-resolved standalone question when this
    // is a genuine follow-up; every other use of `query` below (diagram
    // intent, region detection, the generation prompt itself) keeps the
    // user's original wording untouched.
    const retrievalQuery = conversationHistory.length
      ? await condenseFollowUpQuery(conversationHistory, query)
      : query;

    timer.mark("conversation_memory_and_condense");

    const conversationContext = buildConversationContextForPrompt(
      conversationHistory
    );

    const knownPatterns = await loadQuestionPatterns();
    const diagramIntent = detectDiagramIntent(query, knownPatterns);
    console.log("📊 Diagram Intent Analysis:", {
      shouldGenerate: diagramIntent.shouldGenerate,
      type: diagramIntent.type,
      confidence: Math.round(diagramIntent.confidence * 100) + "%",
      patterns: diagramIntent.matchedPatterns,
    });

    const region = body.region ?? null;
    const topK = Number.isFinite(body.topK as any)
      ? Math.max(1, Math.min(50, body.topK!))
      : 25;
    const threshold = Number.isFinite(body.threshold as any)
      ? Math.max(0, Math.min(1, body.threshold!))
      : 0.3;
    const includeMetadata = body.includeMetadata !== false;

    const validRegions = ["india", "uk", "usa"];
    if (region && !validRegions.includes(region)) {
      return NextResponse.json(
        {
          success: false,
          error: `Invalid region. Must be one of: ${validRegions.join(", ")}`,
        } satisfies RagResponse,
        { status: 400 }
      );
    }

    const mode = body.mode ?? "auto";
    const voiceMode = body.voiceMode === true;

    let feasibilitySection = "";
    let feasibilityReport: any | undefined = undefined;

    if (mode === "feasibility" && body.feasibilityInputs) {
      try {
        const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || "";
        const feasRes = await fetch(`${baseUrl}/api/feasibility`, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify(body.feasibilityInputs),
        });
        const feasJson = await feasRes.json();
        if (feasRes.ok && feasJson?.success) {
          feasibilityReport = feasJson.feasibilityReport;
          feasibilitySection = `\n\nFEASIBILITY SNAPSHOT (structured data – do not change numbers, just explain logically):\n\n${JSON.stringify(
            feasibilityReport,
            null,
            2
          )}`;
        } else {
          console.warn("Feasibility API error:", feasJson?.error);
        }
      } catch (err) {
        console.error("Error calling /api/feasibility:", err);
      }
    }

    let drawingValidation: any | undefined = undefined;

    if (mode === "feasibility" && body.drawingFile) {
      try {
        const location = body.feasibilityInputs?.city
          ?.toLowerCase()
          .includes("london")
          ? "london"
          : "nyc";

        const drawingFormData = new FormData();

        if (
          body.drawingFile instanceof File ||
          body.drawingFile instanceof Blob
        ) {
          drawingFormData.append("drawing", body.drawingFile);
        } else if (typeof body.drawingFile === "string") {
          console.warn("Drawing file is a string, conversion needed");
        }
        drawingFormData.append("location", location);

        const baseUrl = process.env.NEXT_PUBLIC_BASE_URL || "";
        const drawingRes = await fetch(`${baseUrl}/api/analyze-drawing`, {
          method: "POST",
          body: drawingFormData,
        });

        const drawingAnalysis = await drawingRes.json();

        if (drawingRes.ok && drawingAnalysis?.success) {
          const { validateLondon } = await import(
            "@/lib/validators/london-uk-validator"
          );
          const { validateNYC } = await import(
            "@/lib/validators/nyc-usa-validator"
          );

          drawingValidation =
            location === "london"
              ? validateLondon(drawingAnalysis.analysis)
              : validateNYC(
                  drawingAnalysis.analysis,
                  body.feasibilityInputs?.zoneCode || "R4"
                );

          console.log(
            `✅ Drawing validated: ${drawingValidation.violations.length} violations, ${drawingValidation.warnings.length} warnings`
          );
        } else {
          console.warn("Drawing analysis failed:", drawingAnalysis?.error);
        }
      } catch (err) {
        console.error("Error analyzing drawing:", err);
      }
    }

    console.log("⏱️ STEP 1: starting searchRAG");
    let chunks = await searchRAG(retrievalQuery, region, topK, threshold);
    console.log("⏱️ STEP 1 DONE: searchRAG returned", chunks.length, "chunks");
    timer.mark("embedding_and_vector_and_keyword_search");

    // Merge in any documents the visitor uploaded earlier in THIS
    // conversation (lib/userDocuments.ts) - e.g. a site plan or letter
    // attached above, so "what can be done here as per NPPF" is answered
    // from both that upload and the shared regulatory corpus together.
    // A conversation with no uploads costs one cheap existence check and
    // nothing more (see searchUserDocumentChunks). Merged in ahead of the
    // reranker so the LLM relevance pass judges corpus and upload chunks
    // on equal footing rather than favoring one set by construction.
    if (conversationId) {
      console.log("⏱️ STEP 1.25: searching uploaded documents for this conversation");
      const summarizeIntent = isSummarizeIntent(query);
      const userDocMatches = summarizeIntent
        ? await getAllUserDocumentChunks(conversationId)
        : await searchUserDocumentChunks(conversationId, retrievalQuery);
      if (userDocMatches.length) {
        console.log("⏱️ STEP 1.25 DONE:", userDocMatches.length, "uploaded-document chunks");
        chunks = [...chunks, ...userDocMatches.map(mapUserDocRow)];

        if (summarizeIntent) {
          // The literal query ("summarize this", "give me an overview",
          // etc.) carries no content of its own to search the corpus
          // with, so build a second query from the document's own text
          // and use THAT to pull in genuinely relevant regulatory/
          // database material - this is what lets the summary actually
          // reference the shared corpus instead of generic top hits.
          const docGistQuery = userDocMatches
            .slice(0, 6)
            .map((c) => c.content)
            .join("\n\n")
            .slice(0, 4000);
          if (docGistQuery.trim()) {
            const docGroundedCorpus = await searchRAG(
              docGistQuery,
              region,
              topK,
              threshold
            );
            const seenIds = new Set(chunks.map((c) => c.id));
            for (const c of docGroundedCorpus) {
              if (!seenIds.has(c.id)) {
                chunks.push(c);
                seenIds.add(c.id);
              }
            }
            console.log(
              "⏱️ STEP 1.25b DONE: document-grounded corpus search added",
              docGroundedCorpus.length,
              "candidate chunks"
            );
          }
        }
      }
    }

    console.log("⏱️ STEP 1.5: LLM reranking (Groq)");
    chunks = await rerankWithGroq(retrievalQuery, chunks);
    console.log("⏱️ STEP 1.5 DONE: LLM reranking complete");
    timer.mark("groq_rerank");

    console.log("⏱️ STEP 2: reranking");
    chunks = reRankByCitations(chunks, retrievalQuery);
    chunks = reRankByKeywords(chunks, retrievalQuery);
    chunks = rankRetrievedChunks(retrievalQuery, chunks);
    chunks = diversifyChunks(chunks);
    console.log("⏱️ STEP 2 DONE: reranking complete");
    timer.mark("local_rerank");

    console.log("⏱️ STEP 3: document-region filtering");
    const requestedDocRegion = detectRequestedDocumentRegion(query);
    if (requestedDocRegion) {
      // A visitor's own upload has no region (it isn't part of the
      // region-tagged shared corpus) and must never be dropped here just
      // because the question happens to mention a region like "NPPF" ->
      // uk - that's exactly the case this feature exists for.
      const filtered = chunks.filter(
        (c) => c.doc_kind === "user_upload" || lower(c.region) === requestedDocRegion
      );
      if (filtered.length) {
        chunks = filtered;
      }
    }
    console.log("⏱️ STEP 3 DONE: filtered chunks =", chunks.length);
    timer.mark("region_filter");
    console.log(
      "🔎 TOP RANKED CHUNKS:",
      chunks.slice(0, 12).map((c, i) => ({
        rank: i + 1,
        page: c.page_from,
        heading: c.section_heading,
        hierarchy: c.section_hierarchy,
        clause: c.clause_label,
        citationType: c.citation_type,
        citationValue: c.citation_value,
        tableRefs: c.table_refs,
        topic: c.topic,
        preview: c.content.slice(0, 350),
      }))
    );

    if (
      isThresholdQuery(query) &&
      lower(query).includes("firefighting shaft")
    ) {
      console.log("⏱️ THRESHOLD OVERRIDE: firefighting shaft extraction");

      const relevantThresholdChunks = chunks
        .map((c) => ({
          chunk: c,
          priority: getFirefightingShaftClausePriority(c),
        }))
        .filter(({ priority, chunk }) => {
          const text = normalizedForMatching(chunk.content || "");
          const heading = normalizedForMatching(chunk.section_heading || "");
          const section = normalizedForMatching(chunk.section_hierarchy || "");

          const hasTopic =
            text.includes("firefighting shaft") ||
            heading.includes("firefighting shaft") ||
            section.includes("firefighting shaft") ||
            lower(chunk.clause_label).startsWith("17.") ||
            lower(chunk.citation_value).startsWith("17.");

          return hasTopic && priority > 0;
        })
        .sort(
          (a, b) => b.priority - a.priority || a.chunk.distance - b.chunk.distance
        )
        .map(({ chunk }) => chunk);

      console.log(
        "⏱️ THRESHOLD OVERRIDE DEBUG:",
        relevantThresholdChunks.slice(0, 8).map((c) => ({
          page: c.page_from,
          clause: c.clause_label,
          citation: c.citation_value,
          heading: c.section_heading,
          priority: getFirefightingShaftClausePriority(c),
          preview: sanitizeEvidenceText(c.content).slice(0, 220),
        }))
      );

      const primaryChunks = relevantThresholdChunks.filter((c) => {
        const text = normalizedForMatching(c.content || "");
        const clause = lower(c.clause_label);
        const citation = lower(c.citation_value);

        return (
          clause === "17.2" ||
          citation === "17.2" ||
          text.includes(
            "storey more than 18 m above the fire and rescue service vehicle access level"
          )
        );
      });

      const relatedChunks = relevantThresholdChunks.filter((c) => {
        const clause = lower(c.clause_label);
        const citation = lower(c.citation_value);
        return (
          ["17.3", "17.4", "17.5", "17.6"].includes(clause) ||
          ["17.3", "17.4", "17.5", "17.6"].includes(citation)
        );
      });

      const finalThresholdChunks = [...primaryChunks, ...relatedChunks].slice(
        0,
        4
      );

      const thresholdCitations = dedupeCitations(
        transformChunksForFrontend(finalThresholdChunks)
      ).slice(0, 4);

      const primaryCitation =
        thresholdCitations.find((c) => c.clauseNumber === "17.2") ||
        thresholdCitations[0];
      const relatedCitations = thresholdCitations.filter(
        (c) => c !== primaryCitation
      );

      if (primaryCitation) {
        let answer = `### Direct Answer
A firefighting shaft is required where a building has **a storey more than 18 m above the fire and rescue service vehicle access level**. [${primaryCitation.id}]`;

        if (relatedCitations.length > 0) {
          const relatedRefs = relatedCitations.map((c) => `[${c.id}]`).join(" ");
          answer += `

### Related Provisions
Additional firefighting shaft provisions apply to certain basement conditions and, in some cases, to buildings requiring multiple firefighting shafts. ${relatedRefs}`;
        }

        answer = sanitizeEvidenceText(answer);
        answer += buildReferencesBlock(thresholdCitations, []);

        return NextResponse.json(
          {
            success: true,
            answer,
            data: {
              citations: thresholdCitations,
              query,
              region,
              resultsCount: finalThresholdChunks.length,
              metadata: includeMetadata
                ? calculateMetadata(finalThresholdChunks)
                : undefined,
              references: {
                documents: thresholdCitations,
                web: [],
              },
              missingCoverage: [
                {
                  questionPart: query,
                  resolvedFrom: "document",
                },
              ],
              feasibilityReport,
              drawingValidation,
            },
            metadata: {
              processing_time: Date.now() - start,
              confidence: 74,
              webFallbackUsed: false,
            },
          } satisfies RagResponse,
          { status: 200 }
        );
      }

      console.log(
        "⏱️ THRESHOLD OVERRIDE: no usable citations, continuing normal flow"
      );
    }

    if (isTableQuery(query)) {
      console.log("⏱️ TABLE OVERRIDE: attempting direct numeric extraction");

      const relevantTableChunks = chunks
        .filter((c) => {
          const t = lower(c.content);
          return (
            t.includes("table 2.1") ||
            t.includes("travel distance") ||
            /\b\d+\s?m\b/.test(t)
          );
        })
        .slice(0, 8);

      const combinedTableText = relevantTableChunks.map((c) => c.content).join("\n");
      const extractedDistances = combinedTableText.match(/\b\d+\s?m\b/gi) || [];

      const cleanedDistances = extractedDistances.filter((d) => {
        const val = parseInt(d, 10);
        return val >= 10 && val <= 120;
      });

      const uniqueDistances = Array.from(
        new Set(cleanedDistances.map((x) => x.trim()))
      );

      if (uniqueDistances.length > 0) {
        const tableCitations = dedupeCitations(
          transformChunksForFrontend(relevantTableChunks)
        ).slice(0, 5);

        let answer = `### Direct Answer
The following distance values were extracted from the retrieved Table 2.1 context: ${uniqueDistances.join(", ")}.

### Notes
These values were extracted directly from fragmented table-related chunks. They should be verified against the original table layout in Approved Document B.`;

        answer = sanitizeEvidenceText(answer);

        if (tableCitations.length > 0) {
          answer += buildReferencesBlock(tableCitations, []);
        }

        return NextResponse.json(
          {
            success: true,
            answer,
            data: {
              citations: tableCitations,
              query,
              region,
              resultsCount: relevantTableChunks.length,
              metadata: includeMetadata
                ? calculateMetadata(relevantTableChunks)
                : undefined,
              references: {
                documents: tableCitations,
                web: [],
              },
              missingCoverage: [],
              feasibilityReport,
              drawingValidation,
            },
            metadata: {
              processing_time: Date.now() - start,
              confidence: 60,
              webFallbackUsed: false,
            },
          } satisfies RagResponse,
          { status: 200 }
        );
      }
    }

    console.log("⏱️ STEP 4: building citations");
    let documentCitations = dedupeCitations(transformChunksForFrontend(chunks));
    console.log(
      "⏱️ STEP 4 DONE: document citations =",
      documentCitations.length
    );

    console.log("⏱️ STEP 5: checking web fallback");
    const useWebFallback = shouldUseWebFallback(query, chunks);
    console.log("⏱️ STEP 5 INFO: useWebFallback =", useWebFallback);

    const webCitations = useWebFallback ? await fetchWebFallback(query) : [];

    console.log("⏱️ STEP 5 DONE: web citations =", webCitations.length);
    timer.mark("web_fallback");

    console.log("⏱️ STEP 6: preparing answer gating");
    const topSimilarity = getTopSimilarityScore(chunks);
    console.log("⏱️ STEP 6 INFO: topSimilarity =", topSimilarity.toFixed(3));
    const jurisdictionMismatch = hasJurisdictionMismatch(query, chunks);
    const explicitlyOutside = isOutsideDatasetQuery(query);

    let answerResult: {
      answerMarkdown: string;
      missingCoverage: Array<{
        questionPart: string;
        resolvedFrom: "document" | "web" | "unresolved";
      }>;
    };
    // Tracks whether answerResult actually came from generateAnswer() (i.e.
    // is real LLM-written prose worth grading) vs. one of the canned
    // outside-dataset / partial-coverage messages, which there's no point
    // spending an extra Groq call to fact-check.
    let usedGeneratedAnswer = false;

    const noDocumentCoverage =
      !chunks.length || explicitlyOutside || jurisdictionMismatch;

    if (noDocumentCoverage && !webCitations.length) {
      console.log("⏱️ STEP 6 RESULT: no document/web coverage - answering via basic-intelligence fallback");
      documentCitations = [];
      usedGeneratedAnswer = true;
      answerResult = await generateBasicAnswer(query, conversationContext);
    } else if (noDocumentCoverage) {
      // Not covered by the indexed documents, but the web fallback found
      // something — answer from web context only and say so explicitly,
      // rather than discarding the web results we already fetched.
      console.log("⏱️ STEP 6 RESULT: web-only fallback answer");
      documentCitations = [];
      usedGeneratedAnswer = true;
      const webAnswer = await generateAnswer(
        query,
        [],
        webCitations,
        feasibilitySection,
        drawingValidation,
        conversationContext
      );
      answerResult = {
        answerMarkdown: `${WEB_FALLBACK_NOTICE}\n\n${webAnswer.answerMarkdown}`,
        missingCoverage: webAnswer.missingCoverage,
      };
    } else if (
      !isComparisonQuery(query) &&
      !isTableQuery(query) &&
      !isThresholdQuery(query) &&
      topSimilarity < 0.65
    ) {
      console.log("⏱️ STEP 6 RESULT: partial-coverage fallback");
      answerResult = {
        answerMarkdown: buildPartialCoverageAnswer(),
        missingCoverage: [
          {
            questionPart: query,
            resolvedFrom: "document",
          },
        ],
      };
    } else {
      console.log("⏱️ STEP 7: calling generateAnswer");
      usedGeneratedAnswer = true;
      answerResult = await generateAnswer(
        query,
        chunks,
        webCitations,
        feasibilitySection,
        drawingValidation,
        conversationContext
      );
      console.log("⏱️ STEP 7 DONE: generateAnswer returned");
    timer.mark("answer_generation");
    }

    const answerFailedReliably =
      answerResult.answerMarkdown?.includes(
        "I cannot answer reliably from the indexed documents."
      ) || false;

    if (answerFailedReliably) {
      documentCitations = documentCitations.slice(0, 3);
    }

    const allCitations = [...documentCitations, ...webCitations];

    const meta = includeMetadata ? calculateMetadata(chunks) : undefined;
    const processing_time = Date.now() - start;
    const avgDistance = meta?.avgDistance ?? 0;

    let confidence = Math.round(
      calculateConfidence(avgDistance, chunks.length) * 100
    );

    const dirtyChunkCount = countDirtyChunks(chunks);
    const dirtyPenalty = Math.min(18, dirtyChunkCount * 4);
    confidence = Math.max(0, confidence - dirtyPenalty);

    if ((!chunks.length || explicitlyOutside || jurisdictionMismatch) && !webCitations.length) {
      confidence = 0;
    } else if ((!chunks.length || explicitlyOutside || jurisdictionMismatch) && webCitations.length > 0) {
      // Web-only answer: cap it below anything document-grounded, but don't
      // zero it out - it's a real (if unverified-against-our-corpus) answer.
      confidence = Math.min(confidence || 45, 45);
    } else if (
      !isComparisonQuery(query) &&
      !isTableQuery(query) &&
      !isThresholdQuery(query) &&
      topSimilarity < 0.65
    ) {
      confidence = Math.min(confidence, 25);
    } else if (answerFailedReliably) {
      confidence = Math.min(confidence, 25);
    }

    console.log("⏱️ STEP 6.5: checking groundedness");
    timer.mark("post_generation_assembly");
    let groundedness: number | null = null;
    let unsupportedClaims: string[] = [];

    if (usedGeneratedAnswer) {
      const groundingChunks = noDocumentCoverage
        ? []
        : chooseChunksForAnswer(query, chunks);
      const groundingResult = await checkGroundedness(
        query,
        answerResult.answerMarkdown,
        groundingChunks,
        webCitations
      );
      groundedness = groundingResult.groundedness;
      unsupportedClaims = groundingResult.unsupportedClaims;
      console.log(
        "⏱️ STEP 6.5 DONE: groundedness =",
        groundedness,
        "unsupportedClaims =",
        unsupportedClaims.length
      );
    } else {
      console.log("⏱️ STEP 6.5 SKIPPED: no generated answer to grade");
    }

    let diagram: DiagramPayload | undefined;
    let svgContent: string | undefined;

    const shouldDiagram =
      diagramIntent.shouldGenerate ||
      body.wantDiagram === true ||
      wantsDiagram(query);

    let cleanedAnswer = forceAtLeastOneInlineCitation(
      answerResult.answerMarkdown,
      documentCitations,
      webCitations
    );

    cleanedAnswer = sanitizeEvidenceText(cleanedAnswer);

    if (shouldDiagram) {
      const kind = pickDiagramKind(query);
      if (kind === "buildable_envelope") {
        diagram = buildBuildableEnvelopeDiagram(query);
      } else {
        const generated = await generateAnnotatedObjectDiagram(query);
        if (generated) diagram = generated;
      }

      if (shouldGenerateDiagram(cleanedAnswer)) {
        const extractedDiagram = extractDiagramSpec(cleanedAnswer);
        if (extractedDiagram) {
          diagram = extractedDiagram;
        }
        cleanedAnswer = removeJsonBlock(cleanedAnswer);
      }

      if (diagram && diagram.kind === "buildable_envelope") {
        svgContent = generateDiagramSVG(diagram);
      }
    }

    const finalAnswer = cleanedAnswer
      .replace(/\n#{1,6}\s+References[\s\S]*$/i, "")
      .trim();

    console.log("⏱️ STEP 8: voiceMode =", voiceMode);
    timer.mark("groundedness_check");
    const speechText = voiceMode
      ? (await humanizeForSpeech(query, finalAnswer)) || undefined
      : undefined;

    timer.mark("voice_rewrite");
    timer.report({
      path: "full_pipeline",
      chunks: chunks.length,
      web_fallback: webCitations.length > 0,
      voice_mode: voiceMode,
    });

    const response: RagResponse = {
      success: true,
      answer: finalAnswer,
      diagram,
      svgContent,
      data: {
        citations: allCitations,
        query,
        region,
        resultsCount: chunks.length,
        metadata: meta,
        references: {
          documents: documentCitations,
          web: webCitations,
        },
        missingCoverage: answerResult.missingCoverage,
        feasibilityReport,
        drawingValidation,
        speechText,
        corrections: termCorrections.length ? termCorrections : undefined,
      },
      metadata: {
        processing_time,
        confidence,
        webFallbackUsed: webCitations.length > 0,
        groundedness,
        unsupportedClaims,
        conversationId: conversationId || undefined,
      },
    };

    if (conversationId) {
      // Stored in the same raw shape the client's own extraction helpers
      // (extractRawCitations/mapBackendCitations, extractDiagram in
      // ChatInterface.tsx) already know how to normalize, so reopening a
      // saved conversation renders the exact same citations/diagram/badges
      // as the live response did - see handleSelectConversation.
      await persistConversationTurn(conversationId, query, finalAnswer, {
        processingtime: processing_time,
        confidence,
        groundedness,
        unsupportedClaims,
        citations: allCitations,
        diagram: diagram || undefined,
      });
    }

    return NextResponse.json(response, { status: 200 });
  } catch (e: any) {
    console.error("❌ RAG API Error:", e);
    return NextResponse.json(
      {
        success: false,
        error: e?.message || "Internal server error",
      } satisfies RagResponse,
      { status: 500 }
    );
  }
}

