function buildReferencesBlock(
  documentCitations: TransformedCitation[],
  webCitations: TransformedCitation[]
): string {
  const docRefs = documentCitations.map(
    (c) => `- ${formatVerifiedReference(c)}`
  );

  const webRefs = webCitations.map((c) => {
    const bits = [
      `[${c.id}]`,
      c.title,
      "taken from web",
      `Confidence ${c.confidence}%`,
    ];
    return `- ${bits.join(" — ")}`;
  });

  let out = `\n\n### References`;

  if (docRefs.length > 0) {
    out += `\n\n**Document References**\n${docRefs.join("\n")}`;
  }

  if (webRefs.length > 0) {
    out += `\n\n**Web References**\n${webRefs.join("\n")}`;
  }

  return out;
}

function forceAtLeastOneInlineCitation(
  answer: string,
  documentCitations: TransformedCitation[],
  webCitations: TransformedCitation[]
): string {
  let updated = answer;

  const isFallback =
    updated.includes("I cannot answer reliably from the indexed documents.") ||
    updated.includes("This appears to be outside the indexed dataset.");

  if (isFallback) return updated;

  if (documentCitations.length > 0 && !/\[D\d+\]/.test(updated)) {
    updated += `\n\nPrimary document support: [${documentCitations[0].id}]`;
  }

  if (webCitations.length > 0 && !/\[W\d+\]/.test(updated)) {
    updated += `\n\nMissing parts supplemented from web: [${webCitations[0].id}]`;
  }

  return updated;
}

