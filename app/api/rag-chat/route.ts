function dominantJurisdiction(
  chunks: EnhancedChunk[]
): "uk" | "india" | "usa" | null {
  if (!chunks.length) return null;

  const counts: Record<string, number> = {};
  for (const c of chunks) {
    const key = lower(c.region || c.jurisdiction);
    if (!key) continue;
    counts[key] = (counts[key] || 0) + 1;
  }

  const top =
    Object.entries(counts).sort((a, b) => b[1] - a[1])[0]?.[0] || null;
  if (top === "uk" || top === "india" || top === "usa") return top;
  return null;
}

function hasJurisdictionMismatch(
  query: string,
  chunks: EnhancedChunk[]
): boolean {
  if (isComparisonQuery(query)) return false;

  const requested = detectRequestedJurisdiction(query);
  const dominant = dominantJurisdiction(chunks);

  if (!requested || !dominant) return false;
  return requested !== dominant;
}

function getTopSimilarityScore(chunks: EnhancedChunk[]): number {
  if (!chunks.length) return 0;
  // Deliberately NOT chunks[0]: chunks is sorted by a keyword-boosted
  // finalScore (see rankRetrievedChunks), not by raw distance, so index 0
  // is not guaranteed to be the best actual semantic match. Take the max
  // raw similarity across all retrieved chunks instead, matching how each
  // citation's own confidence badge is computed.
  return chunks.reduce(
    (max, c) => Math.max(max, 1 - (c.distance ?? 1)),
    0
  );
}

